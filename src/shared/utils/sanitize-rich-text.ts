const ALLOWED_TAGS = new Set([
  'B',
  'STRONG',
  'I',
  'EM',
  'U',
  'UL',
  'OL',
  'LI',
  'BR',
  'DIV',
  'P',
  'SPAN',
]);

/** Tags whose content is never meant to be displayed as text — drop them along with their content. */
const REMOVE_WITH_CONTENT = new Set(['SCRIPT', 'STYLE']);

/** Returns the attribute value to keep, or null to drop the attribute entirely. */
type AttributeFilter = (tag: string, name: string, value: string) => string | null;

interface SanitizeRules {
  readonly allowedTags: ReadonlySet<string>;
  readonly filterAttribute?: AttributeFilter;
}

const unwrap = (parent: ParentNode, element: Element): void => {
  while (element.firstChild) {
    parent.insertBefore(element.firstChild, element);
  }
  parent.removeChild(element);
};

const sanitizeAttributes = (element: Element, rules: SanitizeRules): void => {
  Array.from(element.attributes).forEach((attribute) => {
    const kept = rules.filterAttribute?.(
      element.tagName,
      attribute.name,
      attribute.value,
    );
    if (kept) {
      element.setAttribute(attribute.name, kept);
    } else {
      element.removeAttribute(attribute.name);
    }
  });
};

const sanitizeNode = (parent: ParentNode, rules: SanitizeRules): void => {
  Array.from(parent.childNodes).forEach((child) => {
    if (child.nodeType === Node.TEXT_NODE) {
      return;
    }
    if (child.nodeType !== Node.ELEMENT_NODE) {
      parent.removeChild(child);
      return;
    }
    const element = child as Element;
    if (REMOVE_WITH_CONTENT.has(element.tagName)) {
      parent.removeChild(element);
      return;
    }
    sanitizeNode(element, rules);
    if (!rules.allowedTags.has(element.tagName)) {
      unwrap(parent, element);
      return;
    }
    sanitizeAttributes(element, rules);
  });
};

const sanitizeHtml = (html: string, rules: SanitizeRules): string => {
  const template = document.createElement('template');
  template.innerHTML = html;
  sanitizeNode(template.content, rules);
  return template.innerHTML;
};

/**
 * Strips an HTML string down to a small, safe formatting vocabulary (bold/italic/underline/lists)
 * with no attributes — used for the rich-text description field, whose authoring surface only
 * ever produces those tags, but is sanitized again defensively before storage and before render.
 */
export const sanitizeRichText = (html: string): string =>
  sanitizeHtml(html, { allowedTags: ALLOWED_TAGS });

const CELL_TAGS = new Set(['B', 'I', 'S', 'U', 'SPAN', 'BR']);
/** The only inline-style declarations SheetJS's rich-text-to-HTML converter ever emits. */
const CELL_STYLE_PROPS = new Set([
  'font-size',
  'text-decoration',
  'text-underline-style',
]);

const filterCellSpanStyle = (value: string): string | null => {
  const kept = value
    .split(';')
    .map((declaration) => declaration.trim())
    .filter(Boolean)
    .filter((declaration) => {
      const prop = declaration.split(':')[0]?.trim().toLowerCase();
      return prop !== undefined && CELL_STYLE_PROPS.has(prop);
    })
    .join('; ');
  return kept || null;
};

const filterCellAttribute: AttributeFilter = (tag, name, value) =>
  tag === 'SPAN' && name === 'style' ? filterCellSpanStyle(value) : null;

/**
 * Same vocabulary risk as `sanitizeRichText` but for spreadsheet-cell HTML generated by the
 * `xlsx` library's rich-text formatter: keeps bold/italic/underline/strikethrough plus a
 * safelisted `style` on `<span>` (font-size/underline-style only) so cell formatting survives.
 */
export const sanitizeSpreadsheetCellHtml = (html: string): string =>
  sanitizeHtml(html, { allowedTags: CELL_TAGS, filterAttribute: filterCellAttribute });

/** True when a rich-text HTML string has no visible text — e.g. `''`, `<br>`, `<div><br></div>`. */
export const isRichTextEmpty = (html: string): boolean => {
  const template = document.createElement('template');
  template.innerHTML = html;
  return template.content.textContent.trim().length === 0;
};
