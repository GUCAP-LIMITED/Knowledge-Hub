export const flattenCatalog = (
  modules: readonly CatalogModule[],
): readonly CatalogModule[] =>
  modules.flatMap((m) => [m, ...flattenCatalog(m.children ?? [])]);

export const allPermissionKeys = (): readonly string[] =>
  [
    ...new Set(
      flattenCatalog(PERMISSION_CATALOG).flatMap((m) => [m.basePermission, ...m.actions]),
    ),
  ].sort();

